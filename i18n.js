    /**
     * Detects user language & region from browser settings.
     */
    function getDetectedLocale() {
      const rawLocale = navigator.language || (navigator.languages && navigator.languages[0]) || 'en-US';
      let lang = 'en';
      let region = 'US';

      try {
        const locale = new Intl.Locale(rawLocale);
        lang = locale.language || 'en';
        region = locale.region || '';
      } catch (err) {
        const parts = rawLocale.split('-');
        lang = parts[0] || 'en';
        region = parts[1] || '';
      }

      if (!region) {
        const tz = Intl.DateTimeFormat().resolvedOptions().timeZone || '';
        if (tz === 'Asia/Kolkata' || tz === 'Asia/Calcutta') region = 'IN';
        else if (tz.startsWith('America/')) region = 'US';
        else if (tz.startsWith('Europe/London')) region = 'GB';
        else if (tz.startsWith('Europe/Paris')) region = 'FR';
        else if (tz.startsWith('Europe/Berlin')) region = 'DE';
        else if (tz.startsWith('Asia/Tokyo')) region = 'JP';
        else if (tz.startsWith('Asia/Seoul')) region = 'KR';
        else if (tz.startsWith('Asia/Shanghai') || tz.startsWith('Asia/Chongqing')) region = 'CN';
        else if (tz.startsWith('Asia/Taipei')) region = 'TW';
        else if (tz.startsWith('Canada/')) region = 'CA';
        else if (tz.startsWith('Australia/')) region = 'AU';
        else if (tz.startsWith('America/Sao_Paulo')) region = 'BR';
        else region = (lang === 'mr' || lang === 'hi' || lang === 'bn' || lang === 'ta' || lang === 'te') ? 'IN' : 'US';
      }

      return {
        lang: lang.toLowerCase(),
        region: region.toUpperCase(),
        fullCode: `${lang.toLowerCase()}-${region.toUpperCase()}`
      };
    }

    /**
     * Resolves translation string by key with multi-tiered fallback.
     */
    function t(key) {
      const { lang, fullCode } = getDetectedLocale();
      const currentDictionary =
        I18N_TRANSLATIONS[fullCode.toLowerCase()] ||
        I18N_TRANSLATIONS[lang] ||
        I18N_TRANSLATIONS.en;
      return currentDictionary[key] || I18N_TRANSLATIONS.en[key] || '';
    }

    /**
     * Applies static translations to existing HTML elements, including category pills.
     */
    function applyStaticUiTranslations() {
      const { lang } = getDetectedLocale();
      document.documentElement.lang = lang;
      document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';

      document.title = t('pageTitle');

      const titleEl = document.getElementById('widget-title-text');
      if (titleEl) titleEl.textContent = t('headerTitle');

      const refreshBtn = document.getElementById('refresh-news-btn');
      if (refreshBtn) refreshBtn.textContent = t('refreshBtn');

      const loadingEl = document.getElementById('news-loading-text');
      if (loadingEl) loadingEl.textContent = t('loading');

      // Update Category Pill labels
      document.querySelectorAll('.cat-text').forEach(el => {
        const i18nKey = el.getAttribute('data-i18n');
        if (i18nKey && t(i18nKey)) {
          el.textContent = t(i18nKey);
        }
      });
    }

    /**
     * Formats Google News RSS parameters: "hl=xx-XX&gl=XX&ceid=XX:xx"
     */
    function getGoogleNewsParams() {
      const { lang, region, fullCode } = getDetectedLocale();
      return `hl=${fullCode}&gl=${region}&ceid=${region}:${lang}`;
    }
