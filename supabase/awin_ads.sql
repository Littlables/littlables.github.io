-- Awin affiliate integration tables.
-- Run this in the Supabase SQL editor (same as news_ingestion.sql).
-- The Cloudflare Worker syncs Awin programs + products here via the
-- service_role key; the worker's /ads endpoint serves them to the site
-- and the admin panel manages them.

create table if not exists public.awin_programs (
  advertiser_id bigint primary key,
  name text not null,
  description text,
  logo_url text,
  display_url text,
  click_through_url text not null,
  primary_region text,
  primary_sector text,
  currency_code text,
  status text,
  commission jsonb,
  -- Littlables category override (childcare|animals|arts|tech|world|uplifting|all).
  -- Null = unmapped; set in the admin panel or by the sync's sector mapping.
  category text,
  enabled boolean not null default true,
  raw jsonb,
  synced_at timestamptz not null default now()
);

create table if not exists public.awin_products (
  id text primary key,
  advertiser_id bigint not null references public.awin_programs(advertiser_id) on delete cascade,
  title text not null,
  description text,
  link text,
  tracked_url text,
  image_link text,
  additional_images jsonb,
  price numeric,
  sale_price numeric,
  currency_code text,
  brand text,
  availability text,
  category text,
  enabled boolean not null default true,
  raw jsonb,
  synced_at timestamptz not null default now()
);
create index if not exists awin_products_advertiser_idx on public.awin_products (advertiser_id);
create index if not exists awin_products_category_idx on public.awin_products (category) where enabled;

create table if not exists public.awin_sync_runs (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  status text not null default 'running',
  steps jsonb,
  error text
);

-- The worker uses the service_role key; ensure it has full access.
-- (Supabase does not always apply default privileges to tables created
-- via psql/migrations, causing 42501 permission denied errors.)
grant all on public.awin_programs to service_role;
grant all on public.awin_products to service_role;
grant all on public.awin_sync_runs to service_role;
grant usage, select on all sequences in schema public to service_role;
