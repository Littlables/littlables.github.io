-- Provider retry queue: rate-limited (or failed) provider/category fetches
-- are re-queued here instead of failing over to another provider.
-- The hourly cron drains due retries before the normal sync.

CREATE TABLE IF NOT EXISTS public.provider_retry_queue (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider text NOT NULL,
  category text NOT NULL DEFAULT 'all',
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'running', 'done', 'failed')),
  not_before timestamptz NOT NULL DEFAULT now(),
  attempts integer NOT NULL DEFAULT 0,
  max_attempts integer NOT NULL DEFAULT 5,
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (provider, category)
);

CREATE INDEX IF NOT EXISTS idx_retry_queue_due
  ON public.provider_retry_queue (status, not_before)
  WHERE status = 'pending';

-- Service role needs full access (worker reads/writes); no RLS policies needed
-- beyond the grant since this table is worker-internal.
GRANT SELECT, INSERT, UPDATE, DELETE ON public.provider_retry_queue TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.provider_retry_queue_id_seq TO service_role;
