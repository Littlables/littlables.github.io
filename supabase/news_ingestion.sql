create or replace function public.claim_news_provider_sync(
  p_provider text,
  p_updated_by text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  claimed_provider text;
begin
  insert into public.news_provider_sync (
    provider,
    status,
    started_at,
    last_attempt_at,
    last_error,
    updated_by,
    updated_at
  )
  values (
    p_provider,
    'running',
    now(),
    now(),
    null,
    p_updated_by,
    now()
  )
  on conflict (provider) do update
  set
    status = 'running',
    started_at = now(),
    last_attempt_at = now(),
    last_error = null,
    updated_by = excluded.updated_by,
    updated_at = now()
  where public.news_provider_sync.status <> 'running'
     or public.news_provider_sync.started_at < now() - interval '20 minutes'
  returning provider into claimed_provider;

  return claimed_provider is not null;
end;
$$;

revoke all on function public.claim_news_provider_sync(text, text) from public, anon, authenticated;
grant execute on function public.claim_news_provider_sync(text, text) to service_role;

